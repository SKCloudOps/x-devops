#!/bin/bash

# Setup script for Daily Repository Reports
# This script helps configure Gmail credentials and automate reporting

set -e

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}========================================${NC}"
echo -e "${BLUE}Daily Repository Report Setup${NC}"
echo -e "${BLUE}========================================${NC}\n"

# Check if Python is installed
if ! command -v python3 &> /dev/null; then
    echo -e "${RED}❌ Python 3 is not installed${NC}"
    echo "Please install Python 3.7 or higher"
    exit 1
fi

PYTHON_VERSION=$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')
echo -e "${GREEN}✅ Python ${PYTHON_VERSION} found${NC}"

# Check if pip packages are installed
echo -e "\n${BLUE}Checking dependencies...${NC}"
if pip3 show python-dotenv &> /dev/null && pip3 show anthropic &> /dev/null; then
    echo -e "${GREEN}✅ All Python dependencies installed${NC}"
else
    echo -e "${YELLOW}⚠️  Installing dependencies...${NC}"
    pip3 install -r requirements.txt
    echo -e "${GREEN}✅ Dependencies installed${NC}"
fi

# Create .env file
echo -e "\n${BLUE}Step 1: Setting up Gmail credentials${NC}"

if [ -f ".env" ]; then
    echo -e "${YELLOW}⚠️  .env file already exists${NC}"
    read -p "Do you want to update it? (y/n) " -n 1 -r
    echo
    if [[ ! $REPLY =~ ^[Yy]$ ]]; then
        echo "Skipping .env configuration"
        ENV_EXISTS=1
    else
        ENV_EXISTS=0
    fi
else
    ENV_EXISTS=0
fi

if [ $ENV_EXISTS -eq 0 ]; then
    echo -e "\n${BLUE}To send reports via Gmail, you need:${NC}"
    echo "1. Your Gmail address"
    echo "2. A 16-character app password (NOT your regular password)"
    echo ""
    echo -e "${YELLOW}Getting an app password:${NC}"
    echo "1. Go to: https://myaccount.google.com/security"
    echo "2. Enable 2-Step Verification (if not already enabled)"
    echo "3. Then go to: https://myaccount.google.com/apppasswords"
    echo "4. Select: Mail → Windows Computer"
    echo "5. Click Generate and copy the 16-character password"
    echo ""

    read -p "Enter your Gmail address: " GMAIL_SENDER
    read -p "Enter the 16-character app password: " GMAIL_PASSWORD
    read -p "Enter recipient email (default: sathishkrcs@gmail.com): " GMAIL_RECIPIENT

    GMAIL_RECIPIENT=${GMAIL_RECIPIENT:-sathishkrcs@gmail.com}

    # Validate email format
    if ! [[ "$GMAIL_SENDER" =~ ^[a-zA-Z0-9._%+-]+@gmail\.com$ ]]; then
        echo -e "${RED}❌ Invalid Gmail address${NC}"
        exit 1
    fi

    # Create .env file
    cat > .env << EOF
# Gmail Configuration for Daily Reports
# Generated by setup_reports.sh on $(date)

GMAIL_SENDER_EMAIL=$GMAIL_SENDER
GMAIL_APP_PASSWORD=$GMAIL_PASSWORD
GMAIL_RECIPIENT_EMAIL=$GMAIL_RECIPIENT
EOF

    echo -e "${GREEN}✅ .env file created${NC}"
    chmod 600 .env
    echo -e "${GREEN}✅ .env file permissions set to 600${NC}"
fi

# Test Gmail connection
echo -e "\n${BLUE}Step 2: Testing Gmail connection${NC}"
read -p "Do you want to send a test report now? (y/n) " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
    echo -e "${BLUE}Running test report...${NC}"
    if python3 daily_repo_report.py; then
        echo -e "${GREEN}✅ Test report sent successfully!${NC}"
    else
        echo -e "${RED}❌ Test report failed${NC}"
        echo "Check your credentials in .env and try again"
        exit 1
    fi
fi

# Setup cron job
echo -e "\n${BLUE}Step 3: Setting up daily automation${NC}"
read -p "Do you want to schedule daily reports? (y/n) " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
    echo -e "\n${YELLOW}Select a schedule:${NC}"
    echo "1) Daily at 9:00 AM"
    echo "2) Daily at 6:00 PM"
    echo "3) Every 6 hours"
    echo "4) Business days (Mon-Fri) at 8:00 AM"
    echo "5) Custom cron expression"
    echo "0) Skip scheduling"

    read -p "Choose an option (0-5): " SCHEDULE_CHOICE

    case $SCHEDULE_CHOICE in
        1)
            CRON_EXPRESSION="0 9 * * *"
            TIME_DESC="9:00 AM daily"
            ;;
        2)
            CRON_EXPRESSION="0 18 * * *"
            TIME_DESC="6:00 PM daily"
            ;;
        3)
            CRON_EXPRESSION="0 */6 * * *"
            TIME_DESC="every 6 hours"
            ;;
        4)
            CRON_EXPRESSION="0 8 * * 1-5"
            TIME_DESC="8:00 AM on weekdays"
            ;;
        5)
            read -p "Enter cron expression (e.g., '0 9 * * *'): " CRON_EXPRESSION
            TIME_DESC="custom schedule"
            ;;
        0)
            echo "Skipping cron setup"
            CRON_EXPRESSION=""
            ;;
        *)
            echo -e "${RED}Invalid option${NC}"
            CRON_EXPRESSION=""
            ;;
    esac

    if [ ! -z "$CRON_EXPRESSION" ]; then
        # Create logs directory
        mkdir -p logs
        echo -e "${GREEN}✅ Created logs directory${NC}"

        # Get the absolute path
        REPO_DIR=$(pwd)
        SCRIPT_PATH="$REPO_DIR/daily_repo_report.py"
        LOG_FILE="$REPO_DIR/logs/daily_report.log"
        PYTHON_PATH=$(which python3)

        # Create cron entry
        CRON_CMD="$CRON_EXPRESSION cd $REPO_DIR && $PYTHON_PATH $SCRIPT_PATH >> $LOG_FILE 2>&1"

        # Check if cron entry already exists
        if (crontab -l 2>/dev/null | grep -F "$SCRIPT_PATH" > /dev/null); then
            echo -e "${YELLOW}⚠️  Cron job already exists for this repository${NC}"
            read -p "Do you want to update it? (y/n) " -n 1 -r
            echo
            if [[ ! $REPLY =~ ^[Yy]$ ]]; then
                echo "Skipping cron update"
                CRON_EXPRESSION=""
            fi
        fi

        if [ ! -z "$CRON_EXPRESSION" ]; then
            # Add cron job
            (crontab -l 2>/dev/null || echo "") | grep -v "$SCRIPT_PATH" | (cat; echo "$CRON_CMD") | crontab -

            echo -e "${GREEN}✅ Cron job scheduled${NC}"
            echo -e "${BLUE}Schedule: $TIME_DESC${NC}"
            echo -e "${BLUE}Command: $CRON_CMD${NC}"
        fi
    fi
fi

# Verify setup
echo -e "\n${BLUE}Step 4: Verifying setup${NC}"

if [ -f ".env" ]; then
    echo -e "${GREEN}✅ .env file exists${NC}"
    if grep -q "GMAIL_SENDER_EMAIL" .env && grep -q "GMAIL_APP_PASSWORD" .env; then
        echo -e "${GREEN}✅ Gmail credentials configured${NC}"
    else
        echo -e "${RED}❌ Gmail credentials not found in .env${NC}"
    fi
else
    echo -e "${YELLOW}⚠️  .env file not found${NC}"
fi

if [ -f "daily_repo_report.py" ]; then
    echo -e "${GREEN}✅ Report script found${NC}"
else
    echo -e "${RED}❌ daily_repo_report.py not found${NC}"
fi

if [ -d "logs" ]; then
    echo -e "${GREEN}✅ Logs directory exists${NC}"
else
    echo -e "${YELLOW}⚠️  Logs directory not created${NC}"
fi

# Final instructions
echo -e "\n${BLUE}========================================${NC}"
echo -e "${GREEN}Setup Complete!${NC}"
echo -e "${BLUE}========================================${NC}"
echo ""
echo -e "${YELLOW}Next steps:${NC}"
echo "1. Test the setup: python3 daily_repo_report.py"
echo "2. Check logs: tail -f logs/daily_report.log"
echo "3. View cron jobs: crontab -l"
echo "4. For detailed help: cat SETUP_DAILY_REPORTS.md"
echo ""
echo -e "${GREEN}Your repository will now receive daily validation reports!${NC}"
echo ""
